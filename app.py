# -*- coding: utf-8 -*-
import os
import streamlit as st
from google import genai
from google.genai import types

st.title("馬柱 ＆ 予想支援アプリ")
st.write("競馬新聞の画像（全体像や見えにくい部分の拡大写真など）を複数枚アップロードできます。AIが情報を総合して厳格にスコア化します。")

# StreamlitのSecretsから自動取得。ダメならサイドバーの入力欄を表示
try:
    api_key = st.secrets["GEMINI_API_KEY"]
except Exception:
    api_key = st.sidebar.text_input("Gemini APIキーを入力してください", type="password")

if api_key:
    try:
        client = genai.Client(api_key=api_key)

        # 複数ファイルのアップロードに対応
        uploaded_files = st.file_uploader(
            "馬柱の画像を選択してください（複数選択可：全体＋拡大など）", 
            type=["jpg", "jpeg", "png"], 
            accept_multiple_files=True
        )

        if uploaded_files:
            for uploaded_file in uploaded_files:
                st.image(uploaded_file, caption=uploaded_file.name, use_container_width=True)
            
            if st.button("この馬柱を解析してスコア化する"):
                with st.spinner("Analyzing multiple images..."):
                    
                    content_parts = []
                    for uploaded_file in uploaded_files:
                        image_bytes = uploaded_file.getvalue()
                        content_parts.append(
                            types.Part.from_bytes(
                                data=image_bytes,
                                mime_type=uploaded_file.type,
                            )
                        )
                    
                    prompt = """
# 役割 (Persona)
あなたはプロの競馬アナリストであり、感情を排してデータと客観的事実に基づき出走馬を数値化・評価するAIです。
提供された複数の出走表（馬柱）画像（全体像や拡大写真など）を相互に参照し、情報を補完し合って正確なデータを読み取ってください。事実に基づかない情報の捏造（ハルシネーション）を厳格に禁止します。

# 採点・評価基準 (100点満点・小数点第一位まで算出)
画像から読み取ったデータをもとに、以下の7項目・合計100点満点（※スコアは必ず「85.5点」のように小数点第一位まで細かく算出）で各馬を厳密に評価してください。

1. ① 近走能力・実績 (20点満点)
   - 「休み明け＝一律減点」は厳禁です。出走間隔・休養期間に応じて採点アプローチを切り替えてください。
   - 【通常馬（間隔0〜5か月）】:
     * 前走内容（8点）：着順だけでなく内容（不利、大外ぶん回し、Hペース先行など）を精査。着差目安は 0.0〜0.2秒（高評価）、0.3〜0.5秒（良）、0.6〜1.0秒（普通）、1.1〜1.5秒（やや減点）、1.6秒以上（大幅減点）。
     * 過去2〜3走（7点）
     * クラス・能力比較（5点）
   - 【長期休養馬（間隔6か月以上）】:
     * 休養前の実績・ラストに見せた能力（8点）
     * 同コース・同距離・同クラス実績（7点）
     * 近い時期の能力・過去実績（5点）
   - 【叩き2走目／3走目補正】:
     * 叩き2走目：前走が明らかな叩き台なら+3点、前走好内容で上積みありなら+2点、通常上積みなら+1点、前走ですでに仕上がっていれば0点、状態悪化は-1〜-2点。
     * 叩き3走目：基本0点（調教良好や内容良好で加点、疲労・成績下降で減点）。
     * 使い詰め（4走目以降）：調教量、馬体重推移、出走間隔から疲労度をチェック。

2. ② コース・距離・馬場適性 (18点満点)
   - コース実績（6点）：同コース・同競馬場・類似条件の好走実績。
   - 距離実績（6点）：今回の距離カテゴリーにおける実績。
   - 馬場実績（6点）：良馬場実績、または道悪実績＋血統の組み合わせ。

3. ③ 調教・仕上がり (17点満点)
   - 時計の速さだけでなく、「全体時計は速いが終い失速」は減点、「終い11秒台で鋭く伸びる」は高評価。最終追い、1週前、併せ馬、厩舎コメント等を加味。
   - 【休み明け馬の仕上がり基準】:
     * 完全仕上がり（16〜17点）/ かなり良い（14〜15点）/ まずまず（11〜13点）/ 余裕あり（8〜10点）/ 叩き台（5〜7点）/ 不足（0〜4点）。
     * 長期休養でも調教高得点なら大きく下げず、低得点なら「今回は叩き台・試走」と判断。
     * 過去の「休み明け実績（鉄砲実績）」を確認し、鉄砲駆けタイプか叩き良化型かを判定して仕上がり点に反映。

4. ④ 脚質・展開 (15点満点)
   - 全馬の脚質（逃げ・先行・好位・差し・追込）を分類。
   - 想定ペース（S/M/H）による展開の利不利（Hペースなら差し・追込をプラス、Sペースなら前有利）を反映。

5. ⑤ 騎手 (12点満点)
   - 当該コース・距離成績、および乗り替わりによるプラス・マイナスを評価。

6. ⑥ 血統 (10点満点)
   - 実績重視。ただし条件変更（芝→ダート、距離短縮/延長、良→重馬場など）の際は血統の重要度を上げる。

7. ⑦ 枠順・馬番 (8点満点)
   - 基本点4点 ＋ コース形態ごとの枠順補正（＋4〜－4点）。

# 処理手順 (Chain of Thought)
1. **データ抽出:** 複数枚の画像から「どこの競馬場の何レースか（例：中山 6レース）」および全頭の情報・休養期間・調教を抽出。
2. **多角採点:** ①〜⑦の基準に従い、休み明けの背景や叩き補正を加味してロジカルに各馬の点数（小数点第一位まで）を算出。
3. **スコア順ソート:** 合計点数が高い順（降順）に並べ替え。
4. **判定ランク付け:** 90.0〜100.0(S), 85.0〜89.9(A+), 80.0〜84.9(A), 75.0〜79.9(B+), 70.0〜74.9(B), 65.0〜69.9(C+), 60.0〜64.9(C), 59.9以下(D)。
5. **期待値の考慮:** 「能力点数 × オッズ」の観点から妙味を考慮し、最終的な印を決定。

# 出力フォーマット
## 📍 対象レース
- **レース名:** （例: 中山 6レース など）

## 🏁 レース傾向・波乱度 5段階判定
- **人気馬の信頼度 (1〜5):** 
- **波乱度・穴馬の台頭余地 (1〜5):** 
- **判定コメント:** 

## 📊 総合評価ランキング（スコア順）
- 順位 / 馬番・馬名 / 合計スコア：**XX.X点**（判定ランク）
- 各馬の評価理由（近走内容、休養明け/叩き評価、適性、調教、展開面のプラスマイナスを簡潔に）

## 🎯 最終推奨印と見解
- ◎ 本命: 
- ○ 対抗: 
- ▲ 単穴: 
- ☆ 穴馬: 
- △ 抑え: 
- ◇ 超穴: 

# 制約事項 (Guardrails)
* **ハルシネーション・捏造の厳禁:** 不鮮明な箇所は勝手に作らず、記載事実のみで採点。
* **情報不足時の対応:** 著しく不足している場合は鮮明な拡大写真の再送を促す。
* **根拠の明示:** スコア算出の根拠となった画像内情報を必ず示す。
                    """

                    content_parts.append(prompt)

                    response = client.models.generate_content(
                        model='gemini-3.6-flash',
                        contents=content_parts
                    )
                    
                    st.subheader("📊 分析結果・予想一覧")
                    st.markdown(response.text)
                    
    except Exception as e:
        st.error(f"エラーが発生しました: {e}")
else:
    st.info("APIキーが設定されていません。")
