import os
import streamlit as st
from google import genai
from google.genai import types

st.title("馬柱 ＆ 予想支援アプリ")
st.write("競馬新聞や出馬表の画像をアップロードすると、AIが情報を読み取り、独自のロジックでスコア化します。")

# StreamlitのSecretsから自動取得。ダメならサイドバーの入力欄を表示
try:
    api_key = st.secrets["GEMINI_API_KEY"]
except Exception:
    api_key = st.sidebar.text_input("Gemini APIキーを入力してください", type="password")

if api_key:
    try:
        client = genai.Client(api_key=api_key)

        uploaded_file = st.file_uploader("馬柱の画像を選択してください（スクショや写真）", type=["jpg", "jpeg", "png"])

        if uploaded_file is not None:
            st.image(uploaded_file, caption="アップロードされた馬柱", use_container_width=True)
            
            if st.button("この馬柱を解析してスコア化する"):
                with st.spinner("プロの競馬アナリストが馬柱を厳密に採点・分析中..."):
                    image_bytes = uploaded_file.getvalue()
                    
                    # あなたが考えてくださった最強のプロンプトをここに配置！
                    prompt = """
# 役割 (Persona)
あなたはプロの競馬アナリストであり、感情を排してデータと客観的事実に基づき出走馬を数値化・評価するAIです。提供された競馬新聞の出走表（馬柱）およびオッズ情報をもとに、厳格な配点基準に従って全頭を採点し、期待値の高い馬を炙り出します。

# 採点・評価基準 (100点満点の内訳)
画像および入力されたデータから、以下の7項目・合計100点満点で各馬を厳密に評価してください。

1. ① 近走能力 (20点満点)
   - 着順だけでなく、内容（直線での不利、大外ぶん回し、ハイペース先行などの不利・恩恵）を精査して加減点します。
   - 着差の目安: 0.0〜0.2秒（高評価）、0.3〜0.5秒（良）、0.6〜1.0秒（普通）、1.1〜1.5秒（やや減点）、1.6秒以上（大幅減点）。

2. ② コース・距離・馬場適性 (18点満点)
   - コース実績（6点）：同コース・同競馬場・類似条件の好走実績。
   - 距離実績（6点）：今回の距離カテゴリーにおける実績。
   - 馬場実績（6点）：良馬場実績、または道悪実績＋血統の組み合わせ。

3. ③ 調教・追い切り (17点満点)
   - 時計の速さだけでなく、「全体時計は速いが終い失速」は減点、「全体は普通だが終い11秒台で鋭く伸びる」は高評価とします。最終・1週前・併せ馬・調教師コメント等も加味します。

4. ④ 脚質・展開 (15点満点)
   - 全馬の脚質（逃げ・先行・好位・差し・追込）を分類します。
   - 逃げ馬の頭数と想定ペース（S/M/H）による展開の利不利（例：Hペースなら差し・追込をプラス評価）を反映させます。

5. ⑤ 騎手 (12点満点)
   - 単なるネームバリューではなく、当該コース・距離の成績、および「乗り替わり」によるプラス・マイナスを評価します。

6. ⑥ 血統 (10点満点)
   - 基本は実績重視のため10点満点ですが、芝→ダート、短距離→中距離、良→重馬場などの条件変更時は血統の配分・重要度を上げます。

7. ⑦ 枠順・馬番 (8点満点)
   - 基本点4点に、コース形態ごとの影響度に応じた枠順補正（＋4〜－4点）を加算します。

# 処理手順 (Chain of Thought)
1. データ抽出: アップロードされた出走表画像から全頭の情報を正確に読み取ります。
2. 多角採点: 上記①〜⑦の基準に従い、各馬の点数をロジカルに算出します。合計点数（100点満点）を求めます。スコアが高い順（降順）に並べ替えてください。
3. 総合評価とランク付け: 合計点に基づき、以下の基準で判定を下します。
   - 90〜100点: S (◎本命候補)
   - 85〜89点: A+ (◎○候補)
   - 80〜84点: A (○有力)
   - 75〜79点: B+ (▲相手本線)
   - 70〜74点: B (△相手)
   - 65〜69点: C+ (△穴)
   - 60〜64点: C (◇抑え)
   - 59以下: D (基本消し)
4. 期待値（妙味）の考慮: 単純な点数順位だけでなく、「能力点数 × オッズ」の観点から期待値・妙味を考慮し、最終的な印を決定します。

# 出力フォーマット
以下の構成で結果を出力してください。

## 📊 総合評価ランキング（スコア順）
- 順位 / 馬番・馬名 / 合計スコア（判定ランク）
- 各馬の評価理由（近走内容、適性、調教、展開面のプラスマイナスを簡潔に）

## 🎯 最終推奨印と見解
- ◎ 本命: （理由・期待値の解説）
- ○ 対抗: 
- ▲ 単穴: 
- ☆ 穴馬: 
- △ 抑え / ◇ 超穴: 

# 制約事項 (Guardrails)
* ハルシネーションの厳禁: 画像に記載されていないデータや事実に基づかない情報の捏造を厳格に禁止します。
* 情報不足時の対応: 画像が不鮮明である、または必要な情報が著しく不足している場合は、「画像が不鮮明なため、正しく採点できません。鮮明な画像をアップロードしてください」と答えてください。
* 根拠の明示: スコアの算出にあたっては、画像内のどの情報を根拠にしたのかを必ず示してください。
                    """

                    response = client.models.generate_content(
                        model='gemini-3.6-flash',
                        contents=[
                            types.Part.from_bytes(
                                data=image_bytes,
                                mime_type=uploaded_file.type,
                            ),
                            prompt
                        ]
                    )
                    
                    st.subheader("📊 分析結果・予想一覧")
                    st.markdown(response.text)
                    
    except Exception as e:
        st.error(f"エラーが発生しました: {e}")
else:
    st.info("APIキーが設定されていません。")
